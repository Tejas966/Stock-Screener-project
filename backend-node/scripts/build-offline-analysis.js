/**
 * Builds the saved offline analysis: data/offline-analysis.json
 *
 *   npm run build:offline-analysis
 *
 * Requires MySQL (company universe) and the Python service running, and the
 * DEMO provider (live provider data changes, so it is never snapshotted).
 * Re-run it whenever the demo dataset or the Python engine changes; the test
 * suite fails if the committed snapshot no longer matches the demo data.
 */
import { writeFileSync } from 'node:fs';
import { config } from '../src/config.js';
import { closePool } from '../src/db/pool.js';
import * as companyRepo from '../src/repositories/companyRepo.js';
import { getCompanyBundle, getUniverse } from '../src/services/analysisService.js';
import { SNAPSHOT_PATH } from '../src/services/offlineSnapshot.js';
import { buildOfflineSummary } from '../src/services/offlineSummary.js';
import { getProvider } from '../src/services/providers/index.js';
import { python } from '../src/services/pythonClient.js';

const PEER_METRICS = ['pe_ratio', 'roe', 'operating_margin', 'revenue_growth', 'debt_to_equity'];

async function main() {
  const provider = getProvider();
  if (!provider.isDemo) throw new Error(`Snapshots are only built from the demo dataset (FINANCIAL_PROVIDER is "${config.provider.name}")`);
  if (!(await python.health())) throw new Error(`Python service is not reachable at ${config.services.pythonUrl}; start it first`);

  const universe = await getUniverse();
  if (universe.analysis_source !== 'live') throw new Error('Universe analysis did not come from the live Python service');
  const sectorStats = {};
  for (const slug of new Set(universe.rows.map((r) => r.company.sector?.slug).filter(Boolean))) {
    const rows = universe.rows.filter((r) => r.company.sector?.slug === slug);
    sectorStats[slug] = await python.statistics(Object.fromEntries(PEER_METRICS.map((k) => [k, rows.map((r) => ({ symbol: r.company.symbol, value: r.metrics[k] ?? null }))])));
  }

  const generatedAt = new Date().toISOString();
  const companies = {};
  for (const c of await companyRepo.listAll()) {
    const bundle = await getCompanyBundle(c.symbol);
    if (bundle.analysis_source !== 'live') throw new Error(`${c.symbol}: analysis not live (${bundle.analysis_error?.message})`);
    companies[c.symbol] = {
      input_hash: bundle.analysis_input_hash,
      generated_at: generatedAt,
      analysis: bundle.analysis,
      summary: buildOfflineSummary(bundle, sectorStats[c.sector?.slug] ?? null),
    };
    console.log(`  ${c.symbol.padEnd(14)} ok`);
  }

  const snapshot = {
    _notice: 'Saved offline analysis of the ILLUSTRATIVE demo dataset. Generated by scripts/build-offline-analysis.js; used only when the live Python engine or Gemini is unavailable and the input hash matches.',
    generated_at: generatedAt,
    provider: provider.name,
    engine_version: Object.values(companies)[0]?.analysis?.engine_version ?? null,
    sector_stats: sectorStats,
    companies,
  };
  writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(snapshot)}\n`);
  console.log(`Wrote ${Object.keys(companies).length} companies to ${SNAPSHOT_PATH}`);
}

main()
  .catch((err) => {
    console.error(`Failed: ${err.message}`);
    process.exitCode = 1;
  })
  .finally(() => closePool());
